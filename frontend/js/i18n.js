let currentLang = localStorage.getItem('agriLang') || 'en';
let activeDict = translations[currentLang] || translations.en;

function initI18n() {
    const lang = localStorage.getItem('agriLang') || 'en';
    applyTranslations(lang);

    const select = document.getElementById('langSelect') || document.getElementById('langPicker');
    if (select) select.value = lang;
}

function applyTranslations(lang) {
    const dict = translations[lang];
    if (!dict) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'BUTTON' || el.children.length === 0) {
                el.textContent = dict[key];
            } else {
                const textNode = Array.from(el.childNodes).find(node => node.nodeType === Node.TEXT_NODE);
                if (textNode) textNode.textContent = dict[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) el.placeholder = dict[key];
    });

    document.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
}

function changeLanguage(lang) {
    localStorage.setItem('agriLang', lang);
    applyTranslations(lang);
}

window.translations = translations;
window.applyTranslations = applyTranslations;
window.changeLanguage = changeLanguage;

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
} else {
    initI18n();
}
